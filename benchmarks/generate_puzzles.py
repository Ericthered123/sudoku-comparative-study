def is_solvable(puzzle: str) -> bool:
    grid = [int(c) for c in puzzle]

    def possible(pos, val):
        row, col = divmod(pos, 9)
        box_r, box_c = (row // 3) * 3, (col // 3) * 3
        for i in range(9):
            if grid[row * 9 + i] == val: return False
            if grid[i * 9 + col] == val: return False
        for dr in range(3):
            for dc in range(3):
                if grid[(box_r + dr) * 9 + (box_c + dc)] == val: return False
        return True

    def solve():
        try:
            pos = grid.index(0)
        except ValueError:
            return True
        for val in range(1, 10):
            if possible(pos, val):
                grid[pos] = val
                if solve(): return True
                grid[pos] = 0
        return False

    return solve()


def validate(p: str):
    if len(p) != 81:
        return False, f"longitud {len(p)} ≠ 81"
    if not all(c in '0123456789' for c in p):
        return False, "caracteres inválidos"
    clues = sum(1 for c in p if c != '0')
    if clues < 17:
        return False, f"solo {clues} pistas (mínimo teórico: 17)"
    if clues == 81:
        return False, "ya resuelto (0 vacíos)"
    return True, f"{81-clues} vacíos, {clues} pistas"


def write_puzzles(path: Path, puzzles: list, label: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    valid, bad = [], []

    print(f"\n{'─'*58}")
    print(f"  {label.upper()} — {len(puzzles)} puzzles")
    print(f"{'─'*58}")

    for i, p in enumerate(puzzles, 1):
        ok, msg = validate(p)
        if ok:
            if is_solvable(p):
                valid.append(p)
                print(f"  [{i:02d}] ✓  {msg}")
            else:
                bad.append((i, p, "sin solución"))
                print(f"  [{i:02d}] ✗  sin solución (descartado)")
        else:
            bad.append((i, p, msg))
            print(f"  [{i:02d}] ✗  {msg}")

    with open(path, 'w') as f:
        f.write('\n'.join(valid) + '\n')

    if bad:
        print(f"\n  ⚠  {len(bad)} rechazados — revisalos manualmente")

    empties = [81 - sum(1 for c in p if c != '0') for p in valid]
    avg = sum(empties) / len(empties) if empties else 0
    print(f"\n  → {len(valid)} puzzles escritos en: {path}")
    print(f"  → Celdas vacías: {min(empties, default=0)}–{max(empties, default=0)} (prom. {avg:.1f})")


